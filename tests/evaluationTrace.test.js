const assert = require('assert'), trace = require('../utils/evaluationTrace'), sinkModule = require('../evaluation/tools/evaluation_trace_sink')
const off = trace.create(); off.emit('stage', { raw: 'text' }); assert.strictEqual(off.state.enabled, false)
const sink = sinkModule.create({ id: 'test' }), enabled = trace.create(sink, { case_id: 'synthetic' })
enabled.emit('raw', { raw: '{"diagnosis":"test"}', apiKey: 'secret', image_url: { url: 'data:image/png;base64,private' } })
assert.strictEqual(enabled.state.reference, 'offline-trace:test')
assert.strictEqual(sink.events[0].data.apiKey, '[REDACTED]'); assert.strictEqual(sink.events[0].data.image_url, '[REDACTED]')
assert.strictEqual(sink.events[0].data.raw, '{"diagnosis":"test"}')
const bad = trace.create({ emit() { throw new Error('disk full') } }); bad.emit('final', {}); assert(bad.state.failed)
const bounded = trace.create(sinkModule.create({ maxBytes: 10 })); bounded.emit('raw', { text: 'large' }); assert(bounded.state.failed)
console.log('trace opt-in, privacy and storage failure contracts passed')
