#!/usr/bin/env node
// 只编译已有卡片字段；不把评测标签、别名或典型描述变成病例事实。
const fs=require('fs'),path=require('path'),crypto=require('crypto')
const root=path.resolve(__dirname,'..'),kb=require('../utils/kb'),concepts=require('../utils/clinicalConcepts'),evidence=require('../utils/knowledgeEvidence')
const hash=v=>crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex')
const args=process.argv.slice(2),release=args.includes('--release')?args[args.indexOf('--release')+1]:require('../knowledge/current-release.json').id
function build() {
  const profiles=kb.DISEASE_KB.map(card=>{
    const groups=[]
    for(const field of ['visualSigns','historySigns'])for(const term of card[field]) {
      const concept=concepts.lookup(term)
      if(!concept || groups.some(g=>g.conceptId===concept.conceptId))continue
      groups.push({conditionId:card.id+':'+concept.conceptId,conceptId:concept.conceptId,field,term,sourceFieldHash:hash(card[field]),evidenceStatus:'pending',originalSource:'unknown'})
    }
    return {profileId:card.id+':base',cardId:card.id,species:card.species,applicability:{locations:card.locations},conceptGroups:groups,supportPatterns:[],contradictions:[],retrievalTexts:[card.name].concat(card.aliases,card.visualSigns,card.historySigns,[card.typicalFeatures]),role:'unknown',relations:[],sourceRefs:groups.map(g=>({conditionId:g.conditionId,cardId:card.id,field:g.field,sourceFieldHash:g.sourceFieldHash,sourceStatus:'pending'})),existingClaimRefs:evidence.forCard(card.name).map(c=>({claimId:c.claimId,field:c.field,status:c.status})),evidenceStatus:'pending'}
  })
  return {schemaVersion:'retrieval-profiles-v1',version:'retrieval-profiles-2026.10.11.1',conceptVersion:concepts.VERSION,knowledgeReleaseId:release,sourceHash:hash(kb.DISEASE_KB),provenance:'compiled_existing_card_fields_no_new_clinical_claims',profiles}
}
function bundle(data){return '// Generated by tools/build-retrieval-profiles.js. Do not edit.\nmodule.exports = '+JSON.stringify(Object.assign({contentHash:hash(data)},data))+'\n'}
function run(){const data=build(),json=JSON.stringify(data,null,2)+'\n',js=bundle(data),jf=path.join(root,'knowledge/retrieval-profiles.json'),bf=path.join(root,'utils/retrievalProfileBundle.js')
  if(args.includes('--check')){if(!fs.existsSync(jf)||!fs.existsSync(bf)||fs.readFileSync(jf,'utf8')!==json||fs.readFileSync(bf,'utf8')!==js)throw Error('retrieval profiles stale: source/field hash or release changed')}
  else{fs.writeFileSync(jf,json);fs.writeFileSync(bf,js)}
  console.log(JSON.stringify({profiles:data.profiles.length,sourceHash:data.sourceHash,release,check:args.includes('--check')}))
}
if(require.main===module)run()
module.exports={build,bundle,hash}
